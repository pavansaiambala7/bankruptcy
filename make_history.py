# ─── Helpers ─────────────────────────────────────────────────────────────────

def sh(cmd, env_extra=None):
    env = {**os.environ, **(env_extra or {})}
    return subprocess.run(cmd, shell=True, cwd=REPO,
                          capture_output=True, text=True, env=env)

def write(relpath, content):
    path = os.path.join(REPO, relpath)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)

def read(relpath):
    with open(os.path.join(REPO, relpath), "r", encoding="utf-8") as f:
        return f.read()

def remove(relpath):
    p = os.path.join(REPO, relpath)
    if os.path.exists(p):
        os.remove(p)

def commit(date, msg):
    env = {"GIT_AUTHOR_DATE": date, "GIT_COMMITTER_DATE": date}
    sh("git add -A", env)
    r = sh('git commit --allow-empty -m "' + msg + '" --date="' + date + '"', env)
    ok = "OK" if r.returncode == 0 else ("SKIP(empty)" if "nothing to commit" in r.stdout else "ERR:" + r.stderr[:60])
    print(f"  [{date[:10]}] {msg}  → {ok}")

